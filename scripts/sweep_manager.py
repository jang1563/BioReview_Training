# log-result
# ---------------------------------------------------------------------------


def log_result(args: argparse.Namespace) -> None:
    """Append evaluation result from .summary.json to sweep CSV."""
    if not args.summary.exists():
        print(f"ERROR: summary not found: {args.summary}", file=sys.stderr)
        raise SystemExit(1)

    data = json.loads(args.summary.read_text(encoding="utf-8"))
    metrics = data.get("eval_metrics", {})

    row = {
        "tag": args.tag,
        "model_dir": data.get("model_dir", ""),
        "f1_micro": metrics.get("f1_micro", ""),
        "recall_overall": metrics.get("recall_overall", ""),
        "precision_overall": metrics.get("precision_overall", ""),
        "recall_major": metrics.get("recall_major", ""),
        "n_articles": metrics.get("n_articles", ""),
        "n_tool_concerns": metrics.get("n_tool_concerns", ""),
        "processed": data.get("processed", ""),
        "total_time": data.get("total_time", ""),
        "summary_file": str(args.summary),
    }

    csv_path = args.csv
    csv_path.parent.mkdir(parents=True, exist_ok=True)
    write_header = not csv_path.exists() or csv_path.stat().st_size == 0

    with csv_path.open("a", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(row.keys()))
        if write_header:
            writer.writeheader()
        writer.writerow(row)

    f1 = metrics.get("f1_micro", "N/A")
    print(f"Logged: {args.tag} → F1={f1} → {csv_path}")


# ---------------------------------------------------------------------------
# show-results
# ---------------------------------------------------------------------------


def show_results(args: argparse.Namespace) -> None:
    """Print sorted results table from sweep CSV."""
    if not args.csv.exists():
        print(f"ERROR: CSV not found: {args.csv}", file=sys.stderr)
        raise SystemExit(1)

    with args.csv.open(encoding="utf-8") as f:
        reader = csv.DictReader(f)
        rows = list(reader)

    if not rows:
        print("No results in CSV.")
        return

    # Sort by F1 descending
    def sort_key(r):
        try:
            return float(r.get("f1_micro", 0))
        except (ValueError, TypeError):
            return 0.0

    rows.sort(key=sort_key, reverse=True)

    print(f"\nSweep Results ({len(rows)} experiments)")
    print(f"Source: {args.csv}\n")
    print("| # | Tag | F1 | Recall | Precision | Recall(major) | Articles |")
    print("|---|-----|---:|-------:|----------:|--------------:|---------:|")

    for i, r in enumerate(rows, 1):
        tag = r.get("tag", "?")
        f1 = r.get("f1_micro", "—")
        rec = r.get("recall_overall", "—")
        prec = r.get("precision_overall", "—")
        rmaj = r.get("recall_major", "—")
        n = r.get("n_articles", "—")
        # Format numbers if present
        try:
            f1 = f"{float(f1):.4f}"
        except (ValueError, TypeError):
            pass
        try:
            rec = f"{float(rec):.4f}"
        except (ValueError, TypeError):
            pass
        try:
            prec = f"{float(prec):.4f}"
        except (ValueError, TypeError):
            pass
        try:
            rmaj = f"{float(rmaj):.4f}"
        except (ValueError, TypeError):
            pass
        print(f"| {i} | {tag} | {f1} | {rec} | {prec} | {rmaj} | {n} |")


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Hyperparameter sweep manager for BioReview SFT."
    )
    sub = parser.add_subparsers(dest="command")

    # generate-configs
    gen = sub.add_parser("generate-configs", help="Create variant configs from sweep definition.")
    gen.add_argument(
        "--sweep",
        type=Path,
        required=True,
        help="Sweep definition YAML file.",
    )

    # log-result
    log = sub.add_parser("log-result", help="Append eval result to sweep CSV.")
    log.add_argument("--summary", type=Path, required=True, help=".summary.json file.")
    log.add_argument("--tag", required=True, help="Experiment tag.")
    log.add_argument(
        "--csv",
        type=Path,
        default=Path("results/sweep_results.csv"),
        help="Sweep results CSV path.",
    )

    # show-results
    show = sub.add_parser("show-results", help="Print sorted results table.")
    show.add_argument(
        "--csv",
        type=Path,
        default=Path("results/sweep_results.csv"),
        help="Sweep results CSV path.",
    )

    args = parser.parse_args()

    if args.command == "generate-configs":
        generate_configs(args)
    elif args.command == "log-result":
        log_result(args)
    elif args.command == "show-results":
        show_results(args)
    else:
        parser.print_help()


if __name__ == "__main__":
    main()
