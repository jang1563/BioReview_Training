#!/usr/bin/env python3
"""Hyperparameter sweep manager for BioReview SFT training.

Subcommands:
  generate-configs  Create variant YAML configs + sweep manifest from a definition
  log-result        Append evaluation results from .summary.json to sweep CSV
  show-results      Print sorted results table from sweep CSV

Usage:
  # Generate sweep configs from definition YAML:
  python scripts/sweep_manager.py generate-configs \
      --sweep configs/sweep/stage1_14b.yaml

  # Log a result after training + inference completes:
  python scripts/sweep_manager.py log-result \
      --summary results/sft_eval/model_val_lr_1e4.summary.json \
      --tag lr_1e4 \
      --csv results/sweep_results.csv

  # Show all sweep results:
  python scripts/sweep_manager.py show-results \
      --csv results/sweep_results.csv

Sweep definition YAML format:
  base_config: configs/qwen2.5_14b_qlora.yaml
  output_dir: configs/sweep/stage1_14b
  experiments:
    - tag: baseline
    - tag: lr_1e4
      overrides:
        training.learning_rate: 1.0e-4
    - tag: ep5
      overrides:
        training.num_train_epochs: 5
"""

from __future__ import annotations

import argparse
import copy
import csv
import json
import sys
from pathlib import Path

import yaml


# ---------------------------------------------------------------------------
# generate-configs
# ---------------------------------------------------------------------------


def _set_nested(d: dict, dotted_key: str, value) -> None:
    """Set a value in a nested dict using dot-notation key."""
    keys = dotted_key.split(".")
    for k in keys[:-1]:
        d = d.setdefault(k, {})
    d[keys[-1]] = value


def _get_nested(d: dict, dotted_key: str, default=None):
    """Get a value from nested dict using dot-notation key."""
    keys = dotted_key.split(".")
    for k in keys:
        if not isinstance(d, dict):
            return default
        d = d.get(k, default)
    return d


def generate_configs(args: argparse.Namespace) -> None:
    """Generate variant configs from a sweep definition YAML."""
    sweep_path = args.sweep
    if not sweep_path.exists():
        print(f"ERROR: sweep definition not found: {sweep_path}", file=sys.stderr)
        raise SystemExit(1)

    sweep_def = yaml.safe_load(sweep_path.read_text(encoding="utf-8"))

    base_config_path = Path(sweep_def["base_config"])
    if not base_config_path.is_absolute():
        # Resolve relative to sweep definition file
        base_config_path = sweep_path.parent / base_config_path
    if not base_config_path.exists():
        print(f"ERROR: base config not found: {base_config_path}", file=sys.stderr)
        raise SystemExit(1)

    base_config = yaml.safe_load(base_config_path.read_text(encoding="utf-8"))

    output_dir = Path(sweep_def.get("output_dir", "configs/sweep"))
    if not output_dir.is_absolute():
        output_dir = sweep_path.parent / output_dir
    output_dir.mkdir(parents=True, exist_ok=True)

    experiments = sweep_def.get("experiments", [])
    if not experiments:
        print("ERROR: no experiments defined in sweep YAML.", file=sys.stderr)
        raise SystemExit(1)

    manifest_rows = []
    base_output_dir = base_config.get("output", {}).get("dir", "models/sweep")

    for idx, exp in enumerate(experiments, 1):
        tag = exp["tag"]
        overrides = exp.get("overrides", {})

        variant = copy.deepcopy(base_config)

        # Apply overrides
        for key, value in overrides.items():
            _set_nested(variant, key, value)

        # Bug fix #10: auto-set lora_alpha = 2 * lora_r
        if "lora.r" in overrides:
            new_r = overrides["lora.r"]
            variant["lora"]["lora_alpha"] = 2 * new_r

        # Bug fix #8: unique output dir per variant
        variant.setdefault("output", {})["dir"] = f"{base_output_dir}_{tag}"

        # Write variant config
        config_path = output_dir / f"{tag}.yaml"
        header = (
            f"# Auto-generated by sweep_manager.py\n"
            f"# Base: {base_config_path.name}\n"
            f"# Tag: {tag}\n"
        )
        if overrides:
            override_str = ", ".join(f"{k}={v}" for k, v in overrides.items())
            header += f"# Overrides: {override_str}\n"
        header += "\n"

        config_path.write_text(
            header + yaml.dump(variant, default_flow_style=False, sort_keys=False),
            encoding="utf-8",
        )

        manifest_rows.append(
            {
                "index": idx,
                "tag": tag,
                "config_path": str(config_path),
                "base_model": _get_nested(variant, "model.name", ""),
                "output_dir": variant["output"]["dir"],
                "overrides": (
                    "; ".join(f"{k}={v}" for k, v in overrides.items())
                    if overrides
                    else ""
                ),
            }
        )
        print(f"  [{idx}] {tag}: {config_path}")

    # Write manifest CSV
    manifest_path = output_dir / "sweep_manifest.csv"
    with manifest_path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(
            f,
            fieldnames=["index", "tag", "config_path", "base_model", "output_dir", "overrides"],
        )
        writer.writeheader()
        writer.writerows(manifest_rows)

    print(f"\nGenerated {len(experiments)} configs in {output_dir}/")
    print(f"Manifest: {manifest_path}")
    n = len(experiments)
    print(f"\nRecommended SLURM array spec: --array=1-{n}%2")


